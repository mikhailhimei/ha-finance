from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':390,'height':844})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:8765/')
    page.evaluate('''() => {
      document.getElementById('root').remove();document.body.style.margin='0';
      const panel=document.createElement('ha-finance-panel');let cb;window.scheduleCalls=0;
      const data={deposits:[],workers:[],budgets:[]};window.updateWorkers=()=>{data.workers=[{id:'w',name:'Миша',employment:'TK',income:10000000,salary_day:14,advance_day:29}];cb(structuredClone(data))};
      panel.hass={connection:{subscribeMessage:async c=>{cb=c;c(structuredClone(data));return ()=>{}}},callWS:async msg=>{
        if(msg.type==='ha_finance/budget_schedule'){window.scheduleCalls++;const result=[{id:'w:salary',name:'Миша · Зарплата',date:'2026-11-13',amount:10000000},{id:'l:salary',name:'Лена · Зарплата',date:'2026-11-13',amount:5000000},{id:'f:fixed',name:'Аренда',date:'2026-11-06',amount:3000000}];if(window.deferSchedule)return new Promise(resolve=>{window.finishSchedule=()=>{window.deferSchedule=false;resolve(result)}});return result;}
        if(msg.type==='ha_finance/mutate'){
          if(msg.action==='budget_create')data.budgets.push({id:'b',name:'Ноябрь 2026',month:msg.payload.month,expenses:[]});
          if(msg.action==='budget_expense_transferred')data.budgets[0].expenses.find(e=>e.id===msg.payload.expense_id).transferred=msg.payload.transferred;
          if(msg.action==='budget_expense_save')data.budgets[0].expenses.push({...msg.payload,id:'e'});
          if(msg.action==='budget_clone'){const source=data.budgets.find(b=>b.id===msg.payload.budget_id);data.budgets.push({...structuredClone(source),id:'clone',month:msg.payload.month,name:'Декабрь 2026',expenses:source.expenses.map(e=>({...e,id:'copy'+e.id,month:msg.payload.month}))})}if(msg.action==='budget_delete')data.budgets=data.budgets.filter(b=>b.id!==msg.payload.budget_id);if(msg.action==='budget_part_save'){const expense=data.budgets[0].expenses.find(e=>e.id===msg.payload.expense_id);expense.children??=[];if(msg.payload.part_id)Object.assign(expense.children.find(p=>p.id===msg.payload.part_id),msg.payload);else expense.children.push({...msg.payload,id:'part'})}if(msg.action==='budget_part_delete')data.budgets[0].expenses[0].children=[];if(msg.action==='budget_expense_delete')data.budgets[0].expenses=[];
          cb(structuredClone(data));
        }return structuredClone(data);
      }};document.body.append(panel);
    }''')
    panel=page.locator('ha-finance-panel')
    panel.get_by_role('button',name='Открыть разделы финансов').click()
    panel.get_by_role('button',name='Распределение бюджета',exact=True).click()
    panel.get_by_role('button',name='Создать бюджет',exact=True).click()
    panel.get_by_label('Месяц и год',exact=True).fill('2026-11')
    panel.get_by_role('button',name='Сохранить',exact=True).click()
    panel.locator('.card').click()
    expect(panel.locator('.toolbar')).to_have_count(1)
    expect(panel.locator('.toolbar h1')).to_have_text('Ноябрь 2026')
    expect(panel.get_by_label('Месяц выплат',exact=True)).to_have_count(0)
    expect(panel.locator('.budget-periods button').first).to_contain_text('Посмотреть общий')
    expect(panel.locator('.budget-periods button')).to_have_count(3)
    combined=panel.locator('.budget-periods button').filter(has_text='Миша')
    expect(combined).to_contain_text('Лена')
    expect(combined).to_contain_text('150')
    expect(panel.locator('.budget-overview')).to_have_count(0)
    combined.click()
    expect(panel.locator('.budget-periods')).to_have_count(0)
    expect(panel.locator('.toolbar h1')).to_have_text('13.11.2026')
    expect(panel.locator('.summary .metric').first).to_contain_text('150')
    expect(panel.get_by_text('Трат пока нет. Укажите, на что пойдут деньги.',exact=True)).to_have_count(0)
    calls_before=page.evaluate('window.scheduleCalls')
    page.evaluate('''() => {
      window.skeletonFlashes=0;
      new MutationObserver(records=>{for(const record of records)for(const node of record.addedNodes){if(node.nodeType===1&&(node.matches('.skeleton')||node.querySelector('.skeleton')))window.skeletonFlashes++}}).observe(document.querySelector('ha-finance-panel').shadowRoot,{childList:true,subtree:true});
    }''')
    page.evaluate('window.deferSchedule=true;window.updateWorkers()')
    page.wait_for_function('typeof window.finishSchedule === "function"')
    expect(panel.locator('.budget-overview')).to_be_visible()
    expect(panel.locator('.skeleton')).to_have_count(0)
    assert page.evaluate('window.skeletonFlashes')==0
    page.evaluate('window.finishSchedule()')
    calls_before=page.evaluate('window.scheduleCalls')
    panel.get_by_role('button',name='Добавить трату',exact=True).click()
    expect(panel.get_by_role('dialog',name='Добавить трату').get_by_role('combobox')).to_have_count(0)
    panel.get_by_label('Наименование',exact=True).fill('Здоровье')
    panel.get_by_label('Сумма, ₽',exact=True).fill('11000')
    panel.get_by_label('Комментарий',exact=True).fill('Стоматолог')
    panel.get_by_role('button',name='Сохранить',exact=True).click()
    expect(panel.locator('.budget-expenses')).to_contain_text('Стоматолог')
    assert page.evaluate('window.scheduleCalls')==calls_before
    assert page.evaluate('window.skeletonFlashes')==0
    expect(panel.locator('.summary .metric').last).to_contain_text('139')
    transferred=panel.get_by_role('checkbox',name='Переведено: Здоровье',exact=True)
    expect(transferred).not_to_be_checked()
    transferred.check()
    expect(transferred).to_be_checked()
    expect(panel.locator('.summary .metric').last).to_contain_text('139')
    category_link=panel.get_by_role('button',name='Открыть категорию Здоровье',exact=True)
    assert category_link.bounding_box()['width']>100
    assert category_link.bounding_box()['height']<30
    category_link.click()
    expect(panel.locator('.toolbar h1')).to_have_text('Здоровье')
    expect(panel.locator('.category-summary>.metric')).to_contain_text('11')
    panel.get_by_role('button',name='Добавить',exact=True).click()
    sheet=panel.get_by_role('dialog',name='Добавить подтип',exact=True)
    sheet.get_by_label('Наименование',exact=True).fill('Кровь')
    sheet.get_by_label('Сумма, ₽',exact=True).fill('3000')
    sheet.get_by_label('Комментарий',exact=True).fill('Анализ крови')
    sheet.get_by_role('button',name='Сохранить',exact=True).click()
    expect(panel.locator('.category-parts')).to_contain_text('Кровь')
    expect(panel.locator('.category-totals .metric').last).to_contain_text('8')
    panel.get_by_role('button',name='Действия с подтипом Кровь').click()
    panel.get_by_role('dialog',name='Кровь',exact=True).get_by_role('button',name='Изменить',exact=True).click()
    panel.get_by_label('Сумма, ₽',exact=True).fill('4000')
    panel.get_by_role('button',name='Сохранить',exact=True).click()
    expect(panel.locator('.category-totals .metric').last).to_contain_text('7')
    panel.get_by_role('button',name='Действия с подтипом Кровь').click()
    panel.get_by_role('dialog',name='Кровь',exact=True).get_by_role('button',name='Удалить',exact=True).click()
    expect(panel.locator('.category-parts .expense')).to_have_count(0)
    page.go_back()
    expect(panel.locator('.summary .metric').last).to_contain_text('139')
    panel.get_by_role('button',name='Назад к доходам').click()
    panel.locator('.budget-periods button').first.click()
    expect(panel.locator('.summary .metric').last).to_contain_text('169')
    expect(transferred).to_be_checked()
    transferred.uncheck()
    expect(transferred).not_to_be_checked()
    expect(panel.locator('.summary .metric').last).to_contain_text('169')
    expect(panel.locator('.budget-expense-group')).to_have_count(2)
    expect(panel.locator('.budget-expense-group').filter(has_text='Миша')).to_contain_text('Здоровье')
    panel.get_by_role('button',name='Добавить трату',exact=True).click()
    dates=panel.get_by_role('combobox',name='Дата дохода',exact=True)
    expect(dates.locator('option')).to_have_count(2)
    expect(dates).not_to_contain_text('Миша')
    expect(dates).not_to_contain_text('Лена')
    panel.get_by_role('button',name='Закрыть',exact=True).click()
    panel.get_by_role('button',name='Действия с тратой Здоровье').click()
    panel.get_by_role('dialog',name='Здоровье',exact=True).get_by_role('button',name='Удалить',exact=True).click()
    expect(panel.locator('.summary .metric').last).to_contain_text('180')
    page.go_back()
    expect(panel.locator('.budget-periods')).to_be_visible()
    page.go_back()
    expect(panel.get_by_role('button',name='Создать бюджет',exact=True)).to_be_visible()
    card=panel.get_by_role('button',name='Ноябрь 2026',exact=True)
    panel.get_by_role('button',name='Действия: Ноябрь 2026',exact=True).click()
    action_dialog=panel.get_by_role('dialog',name='Ноябрь 2026',exact=True)
    expect(action_dialog.get_by_role('button',name='Клонировать',exact=True)).to_be_visible()
    action_dialog.get_by_role('button',name='Клонировать',exact=True).click()
    panel.get_by_role('dialog',name='Клонировать бюджет',exact=True).get_by_label('Месяц и год',exact=True).fill('2026-12')
    panel.get_by_role('button',name='Сохранить',exact=True).click()
    expect(panel.get_by_role('button',name='Декабрь 2026',exact=True)).to_be_visible()
    expect(panel.locator('.hold-card').first).to_have_attribute('aria-label','Декабрь 2026')
    panel.get_by_role('button',name='Действия: Ноябрь 2026',exact=True).click()
    panel.get_by_role('dialog',name='Ноябрь 2026',exact=True).get_by_role('button',name='Удалить',exact=True).click()
    confirmation=panel.get_by_role('dialog',name='Удалить бюджет?',exact=True)
    expect(confirmation).to_contain_text('все его траты')
    confirmation.get_by_role('button',name='Отмена',exact=True).click()
    expect(card).to_be_visible()
    card.dispatch_event('pointerdown',{'pointerType':'touch','isPrimary':True,'button':0,'clientX':50,'clientY':100})
    page.wait_for_timeout(700)
    card.dispatch_event('pointerup',{'pointerType':'touch'})
    panel.get_by_role('dialog',name='Ноябрь 2026',exact=True).get_by_role('button',name='Удалить',exact=True).click()
    panel.get_by_role('dialog',name='Удалить бюджет?',exact=True).get_by_role('button',name='Удалить',exact=True).click()
    expect(card).to_have_count(0)
    expect(panel.get_by_role('button',name='Декабрь 2026',exact=True)).to_be_visible()
    expect(panel.locator('.hold-card').first).to_have_attribute('aria-label','Декабрь 2026')
    assert not errors,errors
    browser.close()
    print('PASS: budget creation, income periods, expense/comment save, individual and combined balances, deletion, back navigation')
